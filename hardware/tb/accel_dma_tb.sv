`timescale 1ns / 1ps
//============================================================================
//  accel_dma_tb.sv  -  INTEGRATION: the whole network with the REAL weight DMA
//
//  This is the proof that wgt_dma replaces accel_tb's `initial begin : dma`
//  block without changing a single output bit. Same program, same image, same
//  64 goldens, same argmax, same pass criterion - and no testbench task
//  anywhere between top_seq's `ld_req` and the weight buffers. What answers the
//  handshake here is accel_sys: accel_top plus wgt_dma, issuing INCR bursts at
//  a behavioural AXI4 slave that holds the real blobs.
//
//  ---- nothing is copied from accel_tb -----------------------------------
//
//  The checking is in accel_check.svh, included by both files, and the op table
//  and goldens are in program_ops.svh, generated by the compiler. So the pass
//  criterion is bit-identical by construction rather than by inspection - which
//  matters, because the ONLY thing this testbench is allowed to differ in is who
//  answers `ld_req`. If the checking had been copied, a divergence in it would
//  be indistinguishable from the DMA being right.
//
//  What this file contains that accel_tb does not: the DDR map, the slave model,
//  and the five base-address registers. What it does NOT contain that accel_tb
//  does: fill_stem_weights, fill_dw_weights, fill_pw_weights, fill_params,
//  fill_logit_params, serve_load and the `dma` block - 170 lines of testbench
//  that are now 800 lines of synthesisable RTL - NOR the image-load loop, since
//  DD-032 the image comes from DDR over the same AXI master as the weights.
//
//  ---- what it can catch that wgt_dma_tb cannot --------------------------
//
//  wgt_dma_tb scoreboards writes against an independently computed expectation,
//  which is a stronger check of the DEALING than this file makes. What it cannot
//  see is everything about the handshake in context:
//
//    * the load arriving too LATE - a weight written after op_start would be
//      caught here as a wrong tensor and nowhere else.
//    * the running parameter index across all 64 ops in program order, with the
//      real pchan sequence including the two RES_ADDs and GAP that carry
//      ld_bytes = 0 but still advance it. wgt_dma_tb walks a chosen subset.
//    * ld_done landing as a single edge 64 times, against top_seq's own edge
//      detector rather than against a testbench's model of it (T-10).
//    * the load side not disturbing the datapath: 6,895,780 elements say so.
//
//  ---- it is SLOWER than accel_tb, and that is the trade -----------------
//
//  accel_tb stays the fast path. It answers `ld_req` in two cycles per bank word
//  with no bus modelling at all, and it is the file to run when a datapath
//  change needs checking against the whole network. This one models AR/R
//  channels beat by beat for every one of the ~143,000 weight writes and ~19,000
//  parameter entries, and it is the file to run when anything about the load
//  path changes.
//
//  The slave is configured with NO R-channel holes here (GAP_MASK 0) and a short
//  AR latency: wgt_dma_tb is where stalling behaviour is tested, and burning
//  simulation time on it again in a run this long buys nothing.
//
//  Run:  bash scripts/run_sim.sh accel_dma accel_sys wgt_dma accel_top top_seq \
//          pw_feeder pw_out dw_feeder res_feeder gap_feeder stem_feeder \
//          logit_out out_stage pe_array mac_lane conv1x1 dwconv3x3 \
//          conv3x3_std dw_array stem_array line_buffer avgpool addr_gen \
//          wgt_buffer act_buffer img_buffer param_buffer rq_bank \
//          bias_add requantize
//============================================================================
`include "axi_ddr_model.svh"

module accel_dma_tb;

    // ---- geometry, matching accel_sys's defaults --------------------------
    localparam DATA_W  = 8;
    localparam TM      = 32,  TM_LOG = 5;
    localparam TN      = 16,  TN_LOG = 4;
    localparam TC      = 16,  TC_LOG = 4;
    localparam TS      = 8,   TS_LOG = 3;
    localparam CIN     = 3;
    localparam K       = 3;
    localparam ACC_W   = 26;
    localparam BIAS_W  = 32;
    localparam M0_W    = 32;
    localparam SHIFT_W = 6;
    localparam AA_W    = 16;
    localparam IA_W    = 16;
    localparam PA_W    = 6;
    localparam PW_WA_W = 10;
    localparam DW_WA_W = 6;
    localparam ST_WA_W = 4;
    localparam NI_W    = 8;
    localparam PGA_W   = 9;
    localparam PGW     = 32;
    localparam NLOG    = 4;
    localparam IDX_W   = 2;
    localparam LOG_W   = 16;

    localparam AXI_ADDR_W = 32;
    localparam AXI_DATA_W = 128;
    localparam AXI_ID_W   = 4;

    localparam IH = 224, IW = 224;
    localparam NIN    = CIN*IH*IW;   // 150,528
    localparam MAXOUT = 1204224;     // largest single output tensor
    localparam WBLOB  = 2194880;     // weights.hex
    localparam PBLOB  = 19264;       // params_*.hex, padded to whole tiles

    // ---- the DDR map the PS will have to honour --------------------------
    //  Four regions, deliberately not adjacent and deliberately not all at
    //  round page offsets, so the DMA's burst splitter has to do its job. The
    //  slave answers DECERR outside them, which would surface as dma_error.
    localparam [31:0] WGT_BASE = 32'h1000_0000;
    localparam [31:0] PB_BASE  = 32'h2000_0000;
    localparam [31:0] PM_BASE  = 32'h2400_0000;
    localparam [31:0] PS_BASE  = 32'h2800_0000;
    localparam [31:0] IMG_BASE = 32'h3000_0000;

    // ---- DUT interface ----------------------------------------------------
    logic                      clock, rst_n;
    logic                      start;
    logic [NI_W-1:0]           n_instr;

    logic                      pg_en;
    logic [PGA_W-1:0]          pg_addr;
    logic [PGW-1:0]            pg_data;

    logic                      img_start;
    wire                       img_busy, img_done;

    wire [AXI_ID_W-1:0]   arid;
    wire [AXI_ADDR_W-1:0] araddr;
    wire [7:0]            arlen;
    wire [2:0]            arsize;
    wire [1:0]            arburst;
    wire                  arlock;
    wire [3:0]            arcache;
    wire [2:0]            arprot;
    wire                  arvalid, arready;
    wire [AXI_ID_W-1:0]   rid;
    wire [AXI_DATA_W-1:0] rdata;
    wire [1:0]            rresp;
    wire                  rlast, rvalid, rready;

    wire [NLOG*LOG_W-1:0]      logits;
    wire                       logits_valid;
    wire [IDX_W-1:0]           argmax;
    wire                       argmax_valid;
    wire [NI_W-1:0]            pc;
    wire                       running, done, tag_error;
    wire                       fault;
    wire                       dma_error;

    accel_sys #(
        .DATA_W(DATA_W),
        .TM(TM), .TM_LOG(TM_LOG), .TN(TN), .TN_LOG(TN_LOG),
        .TC(TC), .TC_LOG(TC_LOG), .TS(TS), .TS_LOG(TS_LOG),
        .CIN(CIN), .K(K), .ACC_W(ACC_W), .BIAS_W(BIAS_W), .M0_W(M0_W),
        .SHIFT_W(SHIFT_W),
        .AA_W(AA_W), .IA_W(IA_W), .PA_W(PA_W),
        .PW_WA_W(PW_WA_W), .DW_WA_W(DW_WA_W), .ST_WA_W(ST_WA_W),
        .NI_W(NI_W), .PGA_W(PGA_W), .PW_W(PGW),
        .NLOG(NLOG), .IDX_W(IDX_W), .LOG_W(LOG_W),
        .AXI_ADDR_W(AXI_ADDR_W), .AXI_DATA_W(AXI_DATA_W), .AXI_ID_W(AXI_ID_W)
    ) u_sys (
        .clock(clock), .rst_n(rst_n),
        .start(start), .n_instr(n_instr),
        .wgt_base(WGT_BASE), .pb_base(PB_BASE),
        .pm_base(PM_BASE),   .ps_base(PS_BASE),
        .pg_en(pg_en), .pg_addr(pg_addr), .pg_data(pg_data),
        .img_base(IMG_BASE), .img_start(img_start),
        .img_busy(img_busy), .img_done(img_done),
        .m_axi_arid(arid), .m_axi_araddr(araddr), .m_axi_arlen(arlen),
        .m_axi_arsize(arsize), .m_axi_arburst(arburst), .m_axi_arlock(arlock),
        .m_axi_arcache(arcache), .m_axi_arprot(arprot),
        .m_axi_arvalid(arvalid), .m_axi_arready(arready),
        .m_axi_rid(rid), .m_axi_rdata(rdata), .m_axi_rresp(rresp),
        .m_axi_rlast(rlast), .m_axi_rvalid(rvalid), .m_axi_rready(rready),
        .logits(logits), .logits_valid(logits_valid),
        .argmax(argmax), .argmax_valid(argmax_valid),
        .pc(pc), .running(running), .done(done), .tag_error(tag_error),
        .fault(fault), .dma_error(dma_error)
    );

    axi_ddr_model #(
        .ADDR_W(AXI_ADDR_W), .DATA_W(AXI_DATA_W), .ID_W(AXI_ID_W),
        .WGT_BASE(WGT_BASE), .WGT_N(WBLOB),
        .PB_BASE(PB_BASE), .PM_BASE(PM_BASE), .PS_BASE(PS_BASE), .PN(PBLOB),
        .IMG_BASE(IMG_BASE), .IMG_N(CIN*IH*IW),
        .AR_LAT(3), .GAP_MASK(0)
    ) u_ddr (
        .clock(clock), .rst_n(rst_n), .err_on(1'b0), .gaps_on(1'b0),
        .arid(arid), .araddr(araddr), .arlen(arlen), .arsize(arsize),
        .arburst(arburst), .arvalid(arvalid), .arready(arready),
        .rid(rid), .rdata(rdata), .rresp(rresp), .rlast(rlast),
        .rvalid(rvalid), .rready(rready)
    );

    initial clock = 1'b0;
    always #5 clock = ~clock;

    // ---- memories the testbench itself needs ------------------------------
    //  Only the program, the image and the goldens. The weight and parameter
    //  blobs are the SLAVE's, not this file's: nothing here needs to know what
    //  is in them, which is the difference from accel_tb.
    reg [31:0] prog     [0:511];
    //  img_mem is still declared because program_ops.svh's load_input fills it,
    //  and the golden checks share that file. Nothing here writes it into the
    //  DUT any more - the DMA reads the image from the DDR model instead.
    reg [7:0]  img_mem  [0:NIN-1];
    reg [7:0]  gold_mem [0:MAXOUT-1];
    reg [15:0] gold_log [0:NLOG-1];

    // The per-op geometry and golden-vector table, generated by the compiler.
    `include "program_ops.svh"

    localparam N_OPS = N_PROG_OPS;

    // The checking, shared verbatim with accel_tb. `ACCEL_TB_DMA is NOT defined
    // here, because the DMA is real.
    `define ACCEL_DUT u_sys.u_dut
    `include "accel_check.svh"

    // ======================================================================
    integer i;
    initial begin
        load_op_table;

        $readmemh("../../software/export/program.hex", prog);
        load_input;
        load_gold_logits;

        // The slave gets the blobs; this testbench never looks inside them.
        u_ddr.load("../../software/export/weights.hex",
                   "../../software/export/params_b.hex",
                   "../../software/export/params_m0.hex",
                   "../../software/export/params_shift.hex");
        // The image goes into DDR too now, transposed to HWC by the model
        // (DD-032). This testbench no longer touches img_buffer at all.
        u_ddr.load_img("../../software/golden/healthy_hl6025/000_input.hex",
                       IH, IW, CIN);

        start = 0; n_instr = 0;
        pg_en = 0; pg_addr = 0; pg_data = 0;
        img_start = 0;
        rst_n = 0;
        repeat (4) @(negedge clock);
        rst_n = 1;

        $display("INTEGRATION: accel_sys running the whole network over AXI4");
        $display("  %0d instructions, one image in, %0d logits out", N_OPS, NLOG);
        $display("  the weights come from a behavioural AXI4 slave, not a task");
        $display("  DDR map: wgt 0x%08x  b 0x%08x  m0 0x%08x  shift 0x%08x",
                 WGT_BASE, PB_BASE, PM_BASE, PS_BASE);
        $display("");

        // ---- the program ---------------------------------------------
        for (i = 0; i < 8*N_OPS; i++) begin
            @(negedge clock);
            pg_addr = i[PGA_W-1:0];
            pg_data = prog[i];
            pg_en   = 1'b1;
            @(posedge clock);
            @(negedge clock);
            pg_en = 1'b0;
        end
        $display("loaded %0d program words", 8*N_OPS);

        // ---- the image, over AXI like everything else ----------------
        @(negedge clock);
        img_start = 1'b1;
        @(negedge clock);
        img_start = 1'b0;
        @(posedge img_done);
        @(negedge clock);
        $display("loaded the %0dx%0d image over AXI4 (%0d pixels, DD-032)",
                 IH, IW, IH*IW);
        $display("");

        // ---- go -------------------------------------------------------
        //  `start` is what latches the four base addresses in the DMA and
        //  zeroes its running parameter index, as well as launching the
        //  sequencer. One pulse does both, which is the point of it being the
        //  same signal.
        n_instr = N_OPS[NI_W-1:0];
        @(negedge clock);
        start = 1'b1;
        @(negedge clock);
        start = 1'b0;

        $display("running:");
        wait (done === 1'b1);
        @(negedge clock);

        report_tail;

        // ---- the one check this file adds ------------------------------
        //  The bus. dma_error is sticky, so a single bad beat anywhere in
        //  ~162,000 buffer writes lands here - and if it had been set, the run
        //  would have hung rather than finishing, because the DMA stops pulsing
        //  ld_done. Checking it anyway costs nothing and names the signal.
        $display("");
        if (dma_error) begin
            fails++;
            $display("  [ERR] wgt_dma raised `dma_error`: a read came back with RRESP != OKAY");
        end else
            $display("  [ok ] no dma_error: every AXI read answered OKAY");

        $display("");
        if (fails == 0)
            $display("ALL PASS  (%0d elements bit-exact vs the software model, %0d ops, one whole inference, weights over AXI4)",
                     total, N_OPS);
        else
            $display("FAILED    (%0d mismatches out of %0d)", fails, total);
        $finish;
    end

    initial begin
        #400_000_000;
        $display("FAILED    (timeout)");
        $finish;
    end

endmodule
