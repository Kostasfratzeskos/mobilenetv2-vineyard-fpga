/*============================================================================
 *  test_preproc.c  -  the C front end against the golden tensor, bit for bit
 *
 *  This is the test that closes the project's verification gap. Until now the
 *  chain of evidence started at software/golden/<set>/000_input.hex: the C
 *  reference model reads it, accel_axi_tb.sv checks 6,895,780 elements against
 *  it, and everything in front of it - decode, resize, crop, normalise, quantise
 *  - was done by torchvision on a PC and checked by nothing.
 *
 *  firmware/src/preproc.c now does the crop, normalise and quantise on the
 *  board, and this test checks it produces EXACTLY that same 000_input.hex from
 *  the decoded source image. So the two halves join: RGB in -> the golden
 *  tensor -> 6.9 M elements bit-exact -> the argmax.
 *
 *  The vector is not invented for this test, which is the point. `000_rgb256.bin`
 *  is the actual decoded source JPEG of a tracked golden set, and
 *  `000_input.hex` is the tensor that set's whole 64-layer trace was produced
 *  from. A test against a hand-rolled input would prove the code
 *  self-consistent; this proves it agrees with torchvision on real data.
 *
 *  ---- the cases ----------------------------------------------------------
 *
 *   1  the RGB vector is present and the right length
 *   2  the golden tensor is present and the right length
 *   3  preproc_self_test passes - the table equals the direct arithmetic, and
 *      the FPU rounds to nearest-even
 *   4  preproc_rgb succeeds
 *   5  ALL 150,528 values match the golden exactly          <- the real one
 *   6  the output is not accidentally all one value (a table of zeros would
 *      pass nothing else, but a clamped-everywhere bug is worth ruling out)
 *   7  a non-256x256 image is REFUSED, not resampled
 *   8  a wrong source length is refused
 *   9  a wrong destination length is refused
 *  10  a null pointer is refused
 *  11  the quantisation is monotonic in the input byte, per channel - a
 *      transposed mean/std pair still passes case 5 only if it is the right
 *      pair, but this catches a sign error cheaply and locally
 *  12  every constant in quant_params.h matches software/export/manifest.json
 *
 *  ---- why case 12 exists ------------------------------------------------
 *
 *  quant_params.h is GENERATED by scripts/gen_program.py --emit, and it is also
 *  committed, because the Vitis build and `make test` both need it and neither
 *  should require remembering to run a generator first.
 *
 *  A committed generated file can go stale silently, which is the drift DD-030 is
 *  about. So it is checked the same way accel_csr.h is checked against the RTL in
 *  test_csr_map: parse the SOURCE - manifest.json - and compare. Requantise the
 *  model without re-running the generator and `make test` fails, instead of the
 *  board quantising with last week's scale and classifying confidently.
 *
 *  Run: cd firmware && make test
 *==========================================================================*/
#include <stdio.h>
#include <stdlib.h>
#include <string.h>

#include "preproc.h"

/*  The tracked golden set. The others in software/golden/ are gitignored
 *  (see .gitignore), so this is the one a fresh clone has - and its RGB vector
 *  is committed beside it for exactly that reason. */
#define GOLD_SET "healthy_9111"
#define GOLD_DIR "../software/golden/" GOLD_SET

static int total, fails;

static void ok(int cond, const char *what)
{
    total++;
    if (!cond) {
        fails++;
        printf("  FAIL  %s\n", what);
    } else {
        printf("  ok    %s\n", what);
    }
}

/*  000_input.hex: one byte per line, hex, CHW row-major. */
static int8_t *load_golden(const char *path, size_t want, size_t *got_n)
{
    FILE   *fh = fopen(path, "r");
    int8_t *v;
    size_t  n = 0;
    char    line[64];

    if (!fh)
        return NULL;
    v = malloc(want ? want : 1);
    if (!v) { fclose(fh); return NULL; }

    while (fgets(line, sizeof line, fh)) {
        char *p = line;
        while (*p == ' ' || *p == '\t') p++;
        if (*p == '\n' || *p == '\r' || *p == '\0')
            continue;
        if (n < want)
            v[n] = (int8_t)(unsigned char)strtoul(p, NULL, 16);
        n++;
    }
    fclose(fh);
    *got_n = n;
    return v;
}

static uint8_t *load_bin(const char *path, size_t *got_n)
{
    FILE    *fh = fopen(path, "rb");
    uint8_t *b;
    long     sz;

    if (!fh)
        return NULL;
    fseek(fh, 0, SEEK_END);
    sz = ftell(fh);
    fseek(fh, 0, SEEK_SET);
    if (sz <= 0) { fclose(fh); return NULL; }
    b = malloc((size_t)sz);
    if (!b) { fclose(fh); return NULL; }
    if (fread(b, 1, (size_t)sz, fh) != (size_t)sz) {
        free(b); fclose(fh); return NULL;
    }
    fclose(fh);
    *got_n = (size_t)sz;
    return b;
}

/* ======================================================================
 *  quant_params.h against its source
 * ====================================================================== */
#define MANIFEST_PATH "../software/export/manifest.json"

/*  A crude scanner, not a JSON parser: find "key" and read the number(s) after
 *  the next colon. The same approach test_csr_map takes to Verilog, and for the
 *  same reason - a dependency-free test is worth more here than a general
 *  parser, and the file is generated by a script in this repository so its shape
 *  is not going to surprise us. */
static const char *find_key(const char *buf, const char *key)
{
    char pat[64];
    const char *p;

    snprintf(pat, sizeof pat, "\"%s\"", key);
    p = strstr(buf, pat);
    if (!p)
        return NULL;
    p = strchr(p, ':');
    return p ? p + 1 : NULL;
}

/*  Read up to n doubles, skipping JSON punctuation. Returns how many it got. */
static int read_nums(const char *p, double *out, int n)
{
    int got = 0;

    while (p && *p && got < n) {
        while (*p == ' ' || *p == '\t' || *p == '\n' || *p == '\r'
               || *p == '[' || *p == ',')
            p++;
        if (*p == '-' || *p == '.' || (*p >= '0' && *p <= '9')) {
            char *end;
            out[got++] = strtod(p, &end);
            if (end == p) break;
            p = end;
        } else {
            break;
        }
    }
    return got;
}

static char *slurp(const char *path)
{
    FILE *fh = fopen(path, "rb");
    char *b;
    long  sz;

    if (!fh) return NULL;
    fseek(fh, 0, SEEK_END);
    sz = ftell(fh);
    fseek(fh, 0, SEEK_SET);
    if (sz <= 0) { fclose(fh); return NULL; }
    b = malloc((size_t)sz + 1);
    if (!b) { fclose(fh); return NULL; }
    if (fread(b, 1, (size_t)sz, fh) != (size_t)sz) {
        free(b); fclose(fh); return NULL;
    }
    b[sz] = '\0';
    fclose(fh);
    return b;
}

/*  Exact equality, not a tolerance. gen_program.py writes the constants with
 *  %.17g, which round-trips a double exactly, so anything other than equality
 *  means the header was not generated from this manifest - which is the whole
 *  question. A tolerance here would accept exactly the drift being looked for. */
static void check_manifest(void)
{
    char   *buf = slurp(MANIFEST_PATH);
    double  v[4];
    int     n;

    if (!buf) {
        ok(0, "software/export/manifest.json is readable");
        return;
    }

    n = read_nums(find_key(buf, "input_scale"), v, 1);
    ok(n == 1 && v[0] == (double)QP_INPUT_SCALE,
       "QP_INPUT_SCALE matches the manifest");
    if (n == 1 && v[0] != (double)QP_INPUT_SCALE)
        printf("        header %.17g, manifest %.17g\n",
               (double)QP_INPUT_SCALE, v[0]);

    n = read_nums(find_key(buf, "img_size"), v, 1);
    ok(n == 1 && (unsigned)v[0] == QP_CROP_SIZE,
       "QP_CROP_SIZE matches the manifest's img_size");

    n = read_nums(find_key(buf, "norm_mean"), v, 3);
    ok(n == 3 && v[0] == (double)QP_MEAN_0 && v[1] == (double)QP_MEAN_1
              && v[2] == (double)QP_MEAN_2,
       "QP_MEAN_* matches the manifest's norm_mean");

    n = read_nums(find_key(buf, "norm_std"), v, 3);
    ok(n == 3 && v[0] == (double)QP_STD_0 && v[1] == (double)QP_STD_1
              && v[2] == (double)QP_STD_2,
       "QP_STD_* matches the manifest's norm_std");

    /*  Only the camera app's confidence display uses it, but it is in the
     *  generated header, so it is held to the same rule as the rest. */
    n = read_nums(find_key(buf, "s_logit"), v, 1);
    ok(n == 1 && v[0] == (double)QP_LOGIT_SCALE,
       "QP_LOGIT_SCALE matches the manifest's s_logit");

    /*  The class ORDER, not just the count. A permuted order renames every
     *  prediction and changes no number anywhere, so nothing else here would
     *  notice it. */
    {
        static const char *names[] = QP_CLASS_NAMES;
        const char *p = find_key(buf, "classes");
        unsigned    i;
        int         all = (p != NULL);

        for (i = 0; i < QP_N_CLASSES && all; i++) {
            char pat[128];
            const char *q;
            snprintf(pat, sizeof pat, "\"%s\"", names[i]);
            q = p ? strstr(p, pat) : NULL;
            if (!q) { all = 0; break; }
            p = q + strlen(pat);      /* each must appear AFTER the last */
        }
        ok(all, "QP_CLASS_NAMES matches the manifest's classes, in order");
    }

    free(buf);
}

int main(void)
{
    uint8_t         *rgb;
    int8_t          *want;
    int8_t          *got;
    size_t           rgb_n = 0, want_n = 0;
    preproc_status_t s;
    size_t           i;
    unsigned         c, y, x;
    size_t           nbad = 0, first_bad = 0;
    int              maxdiff = 0;
    int              lo = 127, hi = -128;

    printf("preproc: %ux%u RGB -> %ux%ux%u int8, crop offset %u\n",
           QP_SRC_SIZE, QP_SRC_SIZE, QP_CROP_SIZE, QP_CROP_SIZE, QP_CHANNELS,
           QP_CROP_OFFSET);
    printf("golden set: %s\n\n", GOLD_SET);

    rgb = load_bin(GOLD_DIR "/000_rgb256.bin", &rgb_n);
    if (!rgb) {
        /*  A hard failure, not a skip. A silently skipped test is worse than no
         *  test: `make test` would pass and nobody would know the front end is
         *  unchecked. Same contract as the .hex blobs the simulation needs. */
        printf("  FAIL  %s/000_rgb256.bin is missing\n", GOLD_DIR);
        printf("\n        Generate it with:\n");
        printf("            python scripts/gen_preproc_vectors.py\n");
        printf("\n>> test_preproc FAILED\n");
        return 1;
    }
    ok(rgb_n == PREPROC_SRC_BYTES, "the RGB vector is 196,608 bytes");
    if (rgb_n != PREPROC_SRC_BYTES) {
        printf("        got %lu\n", (unsigned long)rgb_n);
        printf("\n>> test_preproc FAILED\n");
        return 1;
    }

    want = load_golden(GOLD_DIR "/000_input.hex", PREPROC_OUT_BYTES, &want_n);
    if (!want) {
        printf("  FAIL  %s/000_input.hex is missing\n", GOLD_DIR);
        printf("\n>> test_preproc FAILED\n");
        return 1;
    }
    ok(want_n == PREPROC_OUT_BYTES, "the golden tensor is 150,528 values");
    if (want_n != PREPROC_OUT_BYTES) {
        printf("        got %lu\n", (unsigned long)want_n);
        printf("\n>> test_preproc FAILED\n");
        return 1;
    }

    s = preproc_self_test();
    ok(s == PREPROC_OK, "the 3x256 table equals the direct arithmetic, and the "
                        "FPU rounds to nearest-even");
    if (s != PREPROC_OK)
        printf("        %s\n", preproc_strerror(s));

    got = malloc(PREPROC_OUT_BYTES);
    if (!got) { printf("out of memory\n"); return 1; }

    s = preproc_rgb(rgb, QP_SRC_SIZE, QP_SRC_SIZE, rgb_n,
                    got, PREPROC_OUT_BYTES);
    ok(s == PREPROC_OK, "preproc_rgb accepts a 256x256 image");
    if (s != PREPROC_OK)
        printf("        %s\n", preproc_strerror(s));

    /*  The real check. got is HWC, the golden is CHW, so the comparison
     *  transposes rather than assuming the two agree about layout - and the
     *  transpose is the one DD-032 chose, which makes this a check of that
     *  decision too. */
    for (c = 0; c < QP_CHANNELS; c++) {
        for (y = 0; y < QP_CROP_SIZE; y++) {
            for (x = 0; x < QP_CROP_SIZE; x++) {
                size_t hwc = ((size_t)y * QP_CROP_SIZE + x) * QP_CHANNELS + c;
                size_t chw = ((size_t)c * QP_CROP_SIZE + y) * QP_CROP_SIZE + x;
                int    a = got[hwc], b = want[chw];
                if (a != b) {
                    if (!nbad) first_bad = chw;
                    nbad++;
                    if (abs(a - b) > maxdiff) maxdiff = abs(a - b);
                }
            }
        }
    }
    ok(nbad == 0, "all 150,528 values match the golden tensor bit-exactly");
    if (nbad) {
        printf("        %lu differ, max |diff| %d, first at CHW index %lu "
               "(got %d, want %d)\n",
               (unsigned long)nbad, maxdiff, (unsigned long)first_bad,
               (int)got[0], (int)want[first_bad]);
    }

    for (i = 0; i < PREPROC_OUT_BYTES; i++) {
        if (got[i] < lo) lo = got[i];
        if (got[i] > hi) hi = got[i];
    }
    ok(lo != hi, "the output is not a single repeated value");
    printf("        range [%d, %d]\n", lo, hi);

    /*  The refusals. A photograph from a camera is not 256x256, and the naive
     *  bilinear anyone would reach for does NOT match Pillow's antialiased
     *  resampler - so the only honest answers are a verified resampler or a
     *  refusal, and this build refuses. If that ever silently changes, an
     *  arbitrary photo starts producing a confident wrong class. */
    s = preproc_rgb(rgb, 512, 512, rgb_n, got, PREPROC_OUT_BYTES);
    ok(s == PREPROC_E_SIZE, "a 512x512 image is refused, not resampled");

    s = preproc_rgb(rgb, QP_SRC_SIZE, QP_SRC_SIZE, rgb_n - 1,
                    got, PREPROC_OUT_BYTES);
    ok(s == PREPROC_E_SRC_LEN, "a short source buffer is refused");

    s = preproc_rgb(rgb, QP_SRC_SIZE, QP_SRC_SIZE, rgb_n,
                    got, PREPROC_OUT_BYTES - 1);
    ok(s == PREPROC_E_DST_LEN, "a short destination buffer is refused");

    s = preproc_rgb(NULL, QP_SRC_SIZE, QP_SRC_SIZE, rgb_n,
                    got, PREPROC_OUT_BYTES);
    ok(s == PREPROC_E_NULL, "a null source is refused");

    /*  Monotonicity per channel: std and scale are positive, so a brighter
     *  sample must never quantise lower. Cheap, and it localises a sign error to
     *  this function instead of leaving it to show up as a mismatch in case 5. */
    {
        int mono = 1;
        for (c = 0; c < QP_CHANNELS; c++) {
            int prev = -1000;
            for (i = 0; i < 256; i++) {
                int q = preproc_quant_one(c, (uint8_t)i);
                if (q < prev) mono = 0;
                prev = q;
            }
        }
        ok(mono, "the quantisation is non-decreasing in the input byte");
    }

    /*  quant_params.h is generated AND committed, so it is checked against the
     *  manifest it was generated from - see the note at the top. */
    check_manifest();

    printf("\n%d checks, %d failed\n", total, fails);
    if (fails) {
        printf(">> test_preproc FAILED\n");
        return 1;
    }
    printf(">> test_preproc passed - the C front end reproduces the tensor the\n");
    printf("   hardware's 6,895,780-element check starts from, bit for bit\n");
    free(rgb); free(want); free(got);
    return 0;
}
